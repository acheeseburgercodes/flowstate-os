import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results/operations', {recursive:true});
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1600,height:1000},recordVideo:{dir:'test-results/operations',size:{width:1600,height:1000}}});
const page=await context.newPage();
await page.goto('http://127.0.0.1:5173/operations');
await page.waitForTimeout(1500);
async function add(title,skill){await page.getByLabel('Task description').fill(title);await page.getByLabel('Required skill').selectOption(skill);await page.getByRole('button',{name:'Add task',exact:true}).click();await page.waitForTimeout(2200);}
await add('Research the shared workspace requirements','Research');
await add('Implement the workspace startup plan','Code');
await add('Review local approval and privacy boundaries','Review');
await page.getByRole('button',{name:'Switch to light mode'}).click();
await page.waitForTimeout(2200);
await page.screenshot({path:'test-results/operations/light.png'});
await page.getByRole('button',{name:'Pause Implementation specialist'}).click();
await add('Build the resource validation checks','Code');
await page.getByText('No enabled specialist matches Code. Manual assignment required.',{exact:true}).first().waitFor();
await page.getByLabel('Assign to').selectOption('review');
await page.waitForTimeout(1800);
await page.getByRole('button',{name:'Mark assignment reviewed'}).click();
await page.getByLabel('New specialist').fill('Frontend specialist');
await page.getByRole('button',{name:'Add subagent profile'}).click();
await add('Polish the workspace resource panel','Code');
await page.getByRole('button',{name:'Switch to dark mode'}).click();
await page.waitForTimeout(1600);
await page.screenshot({path:'test-results/operations/dark.png'});
await page.getByRole('heading',{name:'Routing decisions'}).scrollIntoViewIfNeeded();
await page.waitForTimeout(3500);
await page.evaluate(()=>window.scrollTo({top:0,behavior:'smooth'}));
await page.waitForTimeout(2500);
await page.reload();
await page.getByText('Polish the workspace resource panel',{exact:true}).first().waitFor();
await page.emulateMedia({reducedMotion:'reduce'});
const motion = await page.locator('.task-row').first().evaluate(element=>getComputedStyle(element).animationName);
if(motion!=='none')throw new Error('Reduced motion must disable task animations');
await page.waitForTimeout(1800);
await context.close();await browser.close();
console.log('Interactive recording complete. Tasks and profiles persist after reload.');
